-- تعبئة `vendor_id` لقيود النقد المحصَّل القائمة.
--
-- لا تغيير مخطط: العمود موجود منذ البداية مع فهرس، لكن مسار الكتابة كان
-- يتركه فارغاً في هذا النوع وحده. فاضطر الدفتر إلى الانضمام إلى `orders`
-- ليعرف بائع القيد — انضمام يُصفّى به، فلا يُستبدل بمنفذ قراءة.
--
-- البائع يُشتقّ من الطلب: هو مصدر الحقيقة نفسه الذي كان الانضمام يقرأ منه،
-- فالنتيجة مطابقة لما كانت تعيده الاستعلامات قبل التعبئة.
UPDATE "ledger_entries" le
SET "vendor_id" = o."vendor_id"
FROM "orders" o
WHERE le."order_id" = o."id"
  AND le."entry_type" = 'cash_collected'
  AND le."vendor_id" IS NULL;
