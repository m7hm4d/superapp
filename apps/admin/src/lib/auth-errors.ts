import { ApiError } from '@superapp/api-client';

/**
 * ترجمة موحّدة لأخطاء مسارات الأمان.
 *
 * كانت كل بطاقة تحمل جدولها، فتتباعد الصياغات ويُنسى رمز في واحدة ويظهر
 * للمستخدم كنصّ إنجليزي غامض.
 */
const AR: Record<string, string> = {
  INVALID_CREDENTIALS: 'كلمة المرور غير صحيحة',
  SECOND_FACTOR_REQUIRED: 'أدخل رمز المصادقة أو رمز استرداد',
  REAUTH_REQUIRED: 'أدخل كلمة المرور ورمز المصادقة لتأكيد هويتك',
  TOTP_INVALID: 'رمز المصادقة غير صحيح — تأكد من التطبيق وحاول مجدداً',
  TOTP_ALREADY_USED: 'استُعمل هذا الرمز — انتظر الرمز التالي في التطبيق',
  TOTP_NOT_ENABLED: 'فعّل المصادقة الثنائية أولاً',
  TOTP_NOT_SETUP: 'ابدأ بالإعداد أولاً ثم أدخل الرمز',
  RECOVERY_CODE_INVALID: 'رمز الاسترداد غير صحيح أو استُعمل من قبل',
  PASSWORD_UNCHANGED: 'الكلمة الجديدة مطابقة للحالية — اختر غيرها',
  VALIDATION_ERROR: 'تحقّق من الحقول: كلمة المرور ١٢ حرفاً فأكثر، والرمز ٦ أرقام',
};

function arabicSeconds(sec: number): string {
  if (sec <= 1) return 'ثانية';
  if (sec === 2) return 'ثانيتين';
  if (sec <= 10) return `${sec} ثوانٍ`;
  return `${sec} ثانية`;
}

/**
 * نصّ عربي لأي خطأ من هذه المسارات.
 *
 * حالتان تستحقان تمييزاً:
 *
 * - **الجلسة المنتهية**: تغيير كلمة المرور يُبطل الجلسات كلها بما فيها
 *   الحالية. فمن حاول عملية أخرى بعده كان يُقذف إلى صفحة الدخول بلا كلمة —
 *   ويظنّ أن عمليته هي التي فشلت. الرسالة تقول ما جرى.
 * - **تجاوز الحدّ**: بلا مدّة تبقى «حاول لاحقاً»، فيعاود فوراً ويُمدّد
 *   الحدّ على نفسه.
 */
export function authErrorAr(e: unknown): string {
  if (!(e instanceof ApiError)) return 'حدث خطأ غير متوقع';

  if (e.status === 429) {
    return e.retryAfterSec
      ? `محاولات كثيرة — انتظر ${arabicSeconds(e.retryAfterSec)} ثم أعد المحاولة.`
      : 'محاولات كثيرة — انتظر قليلاً ثم أعد المحاولة.';
  }
  if (e.code === 'SESSION_REVOKED') {
    return 'انتهت جلستك — غالباً لأن كلمة المرور أو عامل المصادقة تغيّر. سجّل الدخول من جديد.';
  }
  return AR[e.code] ?? `تعذّر تنفيذ العملية (${e.code})`;
}
